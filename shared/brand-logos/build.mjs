// Builds logos.js (the one list of partner company logos) from the SVG files in svg/ and the notes in sources.json,
// then copies it to every page and app that draws logos. See README.md for where each logo came from and the rules.
//   node shared/brand-logos/build.mjs                          write logos.js and its copies
//   node shared/brand-logos/build.mjs --check                  fail if logos.js or a copy is out of date
//   node shared/brand-logos/build.mjs --import <simple-icons>  refresh the single-colour SVGs from a downloaded
//                                                              simple-icons package (npm pack simple-icons@<version>)
// Never edit logos.js or a copy by hand, and never redraw, recolour or stretch a logo: add or swap its SVG file instead.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const SOURCES = join(here, "sources.json");

/** Where each copy lives. The shop reads a TypeScript copy of logos.js; each platform page folder serves its own. */
const PAGE_LOOKS = ["signup/look", "accounts/look", "control-room/look"];
export const COPIES = [
  { from: "logos.js", to: ["apps/shop/src/app/components/brand/brandLogos.ts", ...PAGE_LOOKS.map((d) => `${d}/brand-logos.js`)] },
  { from: "brand-logos.css", to: ["apps/shop/src/app/components/brand/brandLogo.css", ...PAGE_LOOKS.map((d) => `${d}/brand-logos.css`)] },
];

/** The card and wallet marks the storefront draws (footer and book page). */
export const PAYMENT_MARKS = ["visa", "mastercard", "americanexpress", "paypal", "applepay", "googlepay", "afterpay", "klarna"];
const PAYMENT_MARKS_FILE = "apps/shop/src/app/components/brand/paymentMarks.ts";

const readSources = () => JSON.parse(readFileSync(SOURCES, "utf8"));

/** viewBox and inner markup of one SVG file, without the outer tag, titles and empty spacer boxes. */
export function parseSvg(text) {
  const viewBox = /viewBox="([^"]+)"/.exec(text)?.[1];
  if (!viewBox) throw new Error("SVG has no viewBox");
  const body = text
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/<rect fill="none"[^>]*\/>/g, "")
    .replace(/<path d="M[0-9. ]+h[0-9.]+v[0-9.]+H[0-9.]+z" fill="none"\/>/g, "")
    .trim();
  return { viewBox, body };
}

export function build(only = null) {
  const { simpleIconsVersion, logos } = readSources();
  const out = {};
  for (const [id, meta] of Object.entries(logos)) {
    if (only && !only.includes(id)) continue;
    const file = join(here, "svg", `${id}.svg`);
    if (!existsSync(file)) throw new Error(`Missing svg/${id}.svg`);
    const { viewBox, body } = parseSvg(readFileSync(file, "utf8"));
    const full = meta.colors === "full";
    // A single-colour mark can also carry the company's full-colour artwork (full/<id>.svg), used wherever the logo
    // is shown in its own colours; one-colour places (the storefront's payment icons) keep the single-colour mark.
    const fullArt = meta.full ? parseSvg(readFileSync(join(here, "full", `${id}.svg`), "utf8")) : null;
    out[id] = {
      name: meta.name,
      owner: meta.owner,
      // Single-colour marks are drawn in the company's own colour; full-colour ones carry their colours inside.
      color: full ? null : meta.badge?.ink || meta.color,
      // A few companies only show their mark on their own coloured badge (e.g. Mailchimp's black mark on yellow).
      background: meta.badge?.background || null,
      viewBox,
      body,
      source: full ? meta.source : `simple-icons ${simpleIconsVersion} (CC0), from ${meta.source}`,
      guidelines: meta.guidelines || meta.source,
      ...(fullArt ? { full: { viewBox: fullArt.viewBox, body: fullArt.body, source: meta.full.source } } : {}),
    };
  }
  const banner =
    "// GENERATED by shared/brand-logos/build.mjs from shared/brand-logos/svg/ and sources.json. Edit those, never this.\n" +
    "// Company logos are trademarks of their owners, shown only to say this shop works with that company.\n";
  const each = Object.entries(out).map(([id, logo]) => `export const ${id} = ${JSON.stringify(logo, null, 2)};\n`).join("");
  return `${banner}${each}${only ? "" : `export const BRAND_LOGOS = { ${Object.keys(out).join(", ")} };\n`}`;
}

const CSS_BANNER = "/* GENERATED from shared/brand-logos/brand-logos.css by shared/brand-logos/build.mjs. Edit the source, never this copy. */\n";

/** Every file this script writes, with what it should hold. */
export function outputs() {
  const logos = build();
  const css = CSS_BANNER + readFileSync(join(here, "brand-logos.css"), "utf8");
  const files = { "shared/brand-logos/logos.js": logos };
  // The storefront's payment icons get a file of their own, so a shopper's first load carries only these marks.
  files[PAYMENT_MARKS_FILE] = build(PAYMENT_MARKS);
  for (const { from, to } of COPIES) for (const rel of to) files[rel] = from === "logos.js" ? logos : css;
  return files;
}

/** Files that are missing or differ from what this script makes. */
export function stale() {
  return Object.entries(outputs()).filter(([rel, text]) => {
    const file = resolve(root, rel);
    return !existsSync(file) || readFileSync(file, "utf8") !== text;
  }).map(([rel]) => rel);
}

function importSimpleIcons(dir) {
  const data = JSON.parse(readFileSync(join(dir, "data", "simple-icons.json"), "utf8"));
  const icons = Array.isArray(data) ? data : data.icons;
  const bySlug = new Map(icons.map((icon) => [icon.slug, icon]));
  const sources = readSources();
  sources.simpleIconsVersion = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version;
  for (const [id, meta] of Object.entries(sources.logos)) {
    if (meta.colors === "full") continue;
    const icon = bySlug.get(id);
    if (!icon) throw new Error(`simple-icons has no ${id}`);
    copyFileSync(join(dir, "icons", `${id}.svg`), join(here, "svg", `${id}.svg`));
    meta.color = `#${icon.hex}`;
    meta.source = icon.source;
    if (!meta.guidelines && icon.guidelines) meta.guidelines = icon.guidelines;
    if (icon.license) meta.license = icon.license;
  }
  writeFileSync(SOURCES, `${JSON.stringify(sources, null, 2)}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf("--import");
  if (at > 0) importSimpleIcons(resolve(process.argv[at + 1]));
  if (process.argv.includes("--check")) {
    const bad = stale();
    if (bad.length) { console.error(`Out of date (run node shared/brand-logos/build.mjs): ${bad.join(", ")}`); process.exit(1); }
    console.log("Brand logos match their sources.");
  } else {
    for (const [rel, text] of Object.entries(outputs())) {
      const file = resolve(root, rel);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
    console.log(`Wrote ${Object.keys(outputs()).length} files.`);
  }
}
